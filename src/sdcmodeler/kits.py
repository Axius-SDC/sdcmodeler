"""
Write a governed data kit, as SDCStudio answers it, into a Supabase project.

SDCStudio generates a published model's kit (GET /api/v1/dmgen/dms/<ct_id>/supabase_kit/): every file by its
path in the project, the project base's migration and the model's migration, each without a version. This
writes it, as SDCStudio's own project writer does:

    supabase/functions/_shared/sdc/   the kit: runtime/, components/, models/ and models/index.ts
    supabase/functions/gate/          the gate, the one way a record reaches gdr_records
    supabase/migrations/              <version>_sdc_base.sql once, then <version>_sdc_dm_<ct_id>.sql per model

A published component never changes, so a component file that exists and differs is refused, never rewritten.
Each migration is written once, numbered after the project's latest. models/index.ts lists every model in the
kit. Apply with Supabase's own CLI (`supabase db push`, `supabase functions deploy gate`).
"""
from __future__ import annotations

import json
import re
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any, Iterable

KIT = "supabase/functions/_shared/sdc"
MIGRATIONS = "supabase/migrations"
COMPONENTS = f"{KIT}/components/"
VERSIONED = re.compile(r"\d{14}_")


class KitConflictError(Exception):
    """A file the kit would write already exists with other content."""


IDENTIFIER = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]*")


def prop(name: str) -> str:
    """An object key as TypeScript needs it: bare when an identifier, quoted when not (a ct_id may start with a digit)."""
    return name if IDENTIFIER.fullmatch(name) else json.dumps(name)


def models_index(model_files: Iterable[str], generator: str) -> str:
    cts = sorted(m[len("dm-"):-len(".ts")] for m in model_files)
    lines = [f"// Generated by the SDCStudio kit generator {generator}: every model in this kit, by ct_id.",
             "// Rewritten when a model kit is added.", ""]
    lines += [f"import * as dm_{ct} from './dm-{ct}.ts';" for ct in cts]
    lines += ["", "export const models = {", *[f"  {prop(ct)}: dm_{ct}," for ct in cts], "} as const;", ""]
    return "\n".join(lines)


def _write(root: Path, path: str, text: str, written: list[str], replace: bool) -> None:
    target = root / path
    if target.exists():
        if target.read_text(encoding="utf-8") == text:
            return
        if not replace:
            raise KitConflictError(f"{path} exists and differs; a published component never changes")
    target.parent.mkdir(parents=True, exist_ok=True)
    # newline="" keeps the generated text byte for byte on every platform.
    with open(target, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    written.append(path)


def write_kit(root: str | Path, kit: dict[str, Any], now: datetime | None = None) -> list[str]:
    """Write a kit (SDCStudio's supabase_kit answer) into the project at ``root``. Returns the paths written."""
    root = Path(root)
    written: list[str] = []
    # Refuse before writing anything: a differing component is found first, not halfway through.
    for path, text in kit["files"].items():
        target = root / path
        if path.startswith(COMPONENTS) and target.exists() and target.read_text(encoding="utf-8") != text:
            raise KitConflictError(f"{path} exists and differs; a published component never changes")
    for path, text in kit["files"].items():
        # The runtime, the gate and the model files may be regenerated; a component file never differs.
        _write(root, path, text, written, replace=not path.startswith(COMPONENTS))
    models = root / KIT / "models"
    _write(root, f"{KIT}/models/index.ts", models_index((p.name for p in models.glob("dm-*.ts")), kit["generator"]),
           written, replace=True)

    migrations = root / MIGRATIONS
    existing = [p.name for p in migrations.glob("*.sql")] if migrations.exists() else []
    clock = (now or datetime.now(timezone.utc)).replace(microsecond=0)
    latest = max((n[:14] for n in existing if VERSIONED.match(n)), default=None)
    if latest:
        after = datetime.strptime(latest, "%Y%m%d%H%M%S").replace(tzinfo=timezone.utc) + timedelta(seconds=1)
        clock = max(clock, after)
    for migration in [kit["base_migration"], *kit["migrations"]]:
        # Each migration is written once, whatever version it was given.
        if any(n[15:] == migration["name"] for n in existing if VERSIONED.match(n)):
            continue
        _write(root, f"{MIGRATIONS}/{clock.strftime('%Y%m%d%H%M%S')}_{migration['name']}", migration["sql"],
               written, replace=False)
        clock += timedelta(seconds=1)
    return written
