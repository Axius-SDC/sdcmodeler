"""Writing a governed data kit, as SDCStudio's supabase_kit route answers it, into a Supabase project."""
from datetime import datetime, timezone

import pytest

from sdcmodeler.kits import KitConflictError, write_kit

NOW = datetime(2026, 11, 2, 12, 0, 0, tzinfo=timezone.utc)
SDC = "supabase/functions/_shared/sdc"


def kit(ct: str, component: str = "mc-c1", text: str = "export const ctId = 'c1';\n") -> dict:
    return {
        "generator": "4.0.0",
        "models": [{"ctId": ct, "title": ct.upper()}],
        "files": {
            f"{SDC}/runtime/record.ts": "// runtime\n",
            f"{SDC}/components/{component}.ts": text,
            f"{SDC}/models/dm-{ct}.ts": f"export const ctId = '{ct}';\n",
            "supabase/functions/gate/index.ts": "// gate\n",
        },
        "base_migration": {"name": "sdc_base.sql", "sql": "-- base\n"},
        "migrations": [{"ctId": ct, "name": f"sdc_dm_{ct}.sql", "sql": f"-- {ct}\n"}],
    }


def migrations(root):
    return sorted(p.name for p in (root / "supabase" / "migrations").glob("*.sql"))


def test_the_first_kit_writes_the_base_its_files_and_the_index(tmp_path):
    written = write_kit(tmp_path, kit("m1"), now=NOW)
    assert migrations(tmp_path) == ["20261102120000_sdc_base.sql", "20261102120001_sdc_dm_m1.sql"]
    assert f"{SDC}/models/index.ts" in written
    assert (tmp_path / SDC / "models" / "index.ts").read_text() == (
        "// Generated by the SDCStudio kit generator 4.0.0: every model in this kit, by its root element (dm-<ct_id>).\n"
        "// Rewritten when a model kit is added.\n\n"
        "import * as dm_m1 from './dm-m1.ts';\n\n"
        "export const models = {\n  \"dm-m1\": dm_m1,\n} as const;\n"
    )


def test_a_second_model_adds_its_kit_and_one_migration_after_the_others(tmp_path):
    write_kit(tmp_path, kit("m1"), now=NOW)
    written = write_kit(tmp_path, kit("m2"), now=NOW)
    assert migrations(tmp_path)[-1] == "20261102120002_sdc_dm_m2.sql" and len(migrations(tmp_path)) == 3
    assert not any(p.endswith("sdc_base.sql") for p in written), "the base is written once"
    index = (tmp_path / SDC / "models" / "index.ts").read_text()
    assert '  "dm-m1": dm_m1,' in index and '  "dm-m2": dm_m2,' in index


def test_writing_again_writes_nothing(tmp_path):
    write_kit(tmp_path, kit("m1"), now=NOW)
    assert write_kit(tmp_path, kit("m1"), now=NOW) == []


def test_a_component_that_differs_is_refused_before_anything_is_written(tmp_path):
    write_kit(tmp_path, kit("m1"), now=NOW)
    with pytest.raises(KitConflictError, match="a published component never changes"):
        write_kit(tmp_path, kit("m2", text="export const ctId = 'changed';\n"), now=NOW)
    assert not (tmp_path / SDC / "models" / "dm-m2.ts").exists()
    assert len(migrations(tmp_path)) == 2


def test_a_cuid_is_never_a_key_on_its_own(tmp_path):
    # A CUID may start with a digit; models are keyed by their root element, dm-<ct_id>, as the XSD names them.
    write_kit(tmp_path, kit("5scaiw897xhuqa1k8sso932e"), now=NOW)
    index = (tmp_path / SDC / "models" / "index.ts").read_text()
    assert '  "dm-5scaiw897xhuqa1k8sso932e": dm_5scaiw897xhuqa1k8sso932e,' in index
